package com.docintell.entity;

import com.docintell.enums.AnalysisStatus;
import com.docintell.enums.DocumentType;
import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

/**
 * JPA Сущность: Document (Документ)
 *
 * ЧТО ЭТО ТАКОЕ?
 * Сущность (Entity) — это Java-класс, который представляет таблицу в базе данных.
 * Каждое поле класса соответствует столбцу таблицы `documents`.
 *
 * АННОТАЦИИ:
 * @Entity — сообщает JPA/Hibernate, что объекты этого класса нужно сохранять в БД.
 * @Table(name = "documents") — указывает точное имя таблицы в PostgreSQL.
 * @Id и @GeneratedValue — объявляют первичный ключ с автоинкрементом (GENERATED BY DEFAULT AS IDENTITY).
 * @Enumerated(EnumType.STRING) — сохраняет enum как понятный текст ("CONTRACT", "INVOICE"),
 *                                а не как числовой индекс (0, 1). Если порядок в enum изменится,
 *                                данные в БД не испортятся.
 * @OneToMany — связь "Один ко многим". Один документ содержит множество полей (fields)
 *              и множество запусков анализа (analysisResults).
 *              cascade = CascadeType.ALL означает: если удалить документ,
 *              все его поля и результаты анализа удалятся автоматически.
 */
@Entity
@Table(name = "documents")
@Getter
@Setter
@NoArgsConstructor
public class Document {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Тип документа (PASSPORT, CONTRACT, INVOICE и т.д.).
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "document_type", nullable = false)
    private DocumentType documentType = DocumentType.UNKNOWN;

    /**
     * Исходное имя файла при загрузке пользователем.
     */
    @Column(name = "original_filename", nullable = false)
    private String originalFilename;

    /**
     * Уникальное имя файла на диске сервера (UUID), предотвращающее перезапись.
     */
    @Column(name = "stored_filename", nullable = false, unique = true)
    private String storedFilename;

    /**
     * Полный или относительный путь к сохранённому файлу.
     */
    @Column(name = "file_path", nullable = false)
    private String filePath;

    /**
     * MIME-тип файла (например: "application/pdf", "image/png").
     */
    @Column(name = "mime_type", nullable = false)
    private String mimeType;

    /**
     * Размер файла в байтах.
     */
    @Column(name = "file_size", nullable = false)
    private Long fileSize;

    /**
     * Текущий статус обработки (UPLOADED, PROCESSING, COMPLETED, FAILED).
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false)
    private AnalysisStatus status = AnalysisStatus.UPLOADED;

    /**
     * Агрегированная оценка уверенности AI (от 0.0 до 1.0).
     */
    @Column(name = "overall_confidence")
    private Double overallConfidence = 0.0;

    /**
     * Дата и время загрузки.
     */
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * Дата и время последнего обновления.
     */
    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    /**
     * Список извлечённых структурированных полей документа.
     */
    @OneToMany(mappedBy = "document", cascade = CascadeType.ALL, orphanRemoval = true, fetch = FetchType.LAZY)
    @JsonIgnore
    private List<DocumentField> fields = new ArrayList<>();

    /**
     * История запусков AI-анализа для этого документа.
     */
    @OneToMany(mappedBy = "document", cascade = CascadeType.ALL, orphanRemoval = true, fetch = FetchType.LAZY)
    @JsonIgnore
    private List<AnalysisResult> analysisResults = new ArrayList<>();

    /**
     * Жизненный цикл сущности: автоматически проставляет время создания и обновления.
     */
    @PrePersist
    protected void onCreate() {
        this.createdAt = LocalDateTime.now();
        this.updatedAt = LocalDateTime.now();
    }

    @PreUpdate
    protected void onUpdate() {
        this.updatedAt = LocalDateTime.now();
    }

    /**
     * Удобный хелпер-метод для добавления поля и поддержания двунаправленной связи.
     */
    public void addField(DocumentField field) {
        fields.add(field);
        field.setDocument(this);
    }

    public void addAnalysisResult(AnalysisResult result) {
        analysisResults.add(result);
        result.setDocument(this);
    }
}
