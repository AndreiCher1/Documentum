def parse_subdivision_code(code: str) -> Optional[Tuple[str, str, str]]:
    """
    Разбирает код подразделения XXX-XXX.
    Возвращает (код_региона, тип_органа, номер) или None.
    """
    cleaned = re.sub(r'[^0-9]', '', code)
    if len(cleaned) != 6:
        return None
    reg = cleaned[:2]
    org_type = cleaned[2]
    num = cleaned[3:]
    return reg, org_type, num


def get_region_name_by_code(code: str) -> Optional[str]:
    """Возвращает название региона РФ по коду подразделения."""
    parsed = parse_subdivision_code(code)
    if not parsed:
        return None
    reg, _, _ = parsed
    return RUSSIAN_REGIONS.get(reg)


def get_canonical_issued_by(code: str) -> Optional[str]:
    """Возвращает точное эталонное наименование подразделения, если оно есть в базе."""
    cleaned = re.sub(r'[^0-9]', '', code)
    if len(cleaned) == 6:
        formatted = f"{cleaned[:3]}-{cleaned[3:]}"
        return KNOWN_FMS_UNITS.get(formatted)
    return None


def validate_and_refine_issued_by(raw_issued_by: str, subdivision_code: Optional[str]) -> Tuple[str, float]:
    """
    Валидирует и восстанавливает наименование органа выдачи с учетом кода подразделения.
    
    :param raw_issued_by: Сырая строка из OCR / текстовых блоков.
    :param subdivision_code: Код подразделения (XXX-XXX).
    :return: (уточненное_наименование, коэффициент_уверенности)
    """
    if not raw_issued_by and not subdivision_code:
        return "", 0.0

    raw_clean = re.sub(r'\s+', ' ', raw_issued_by or '').strip()

    # 1. Если код подразделения есть в справочнике точных подразделений
    if subdivision_code:
        canon = get_canonical_issued_by(subdivision_code)
        if canon:
            # Если в сыром тексте есть пересечения ключевых слов с каноническим названием
            canon_words = set(w.lower() for w in canon.split() if len(w) > 2)
            raw_words = set(w.lower() for w in raw_clean.split() if len(w) > 2)
            overlap = len(canon_words & raw_words)
            if overlap >= 1 or len(raw_clean) < 10:
                return canon, 0.98

    # 2. Если в сыром тексте присутствуют явные признаки органа выдачи
    valid_indicators = [
        "ОТДЕЛ", "ОВД", "УВД", "МВД", "УФМС", "ФМС", "ПОЛИЦИ",
        "ОКРУГ", "РАЙОН", "ГОРОД", "ОБЛАСТ", "РЕСПУБЛИК", "КРА",
        "ТП", "ОМ", "ПУНКТ"
    ]
    has_indicator = any(ind in raw_clean.upper() for ind in valid_indicators)

    # Проверка на типографский мусор (например, "Паспорт выдан", "Восторт вы", "Личный код")
    junk_patterns = [
        r'паспорт\s*выдан', r'востор[тд]\s*вы', r'дата\s*выдачи',
        r'личный\s*код', r'подпись', r'российская\s*федерация'
    ]
    is_junk = any(re.search(p, raw_clean, re.IGNORECASE) for p in junk_patterns)
    if is_junk and not has_indicator:
        # Это типографская метка, а не значение органа выдачи
        if subdivision_code:
            canon = get_canonical_issued_by(subdivision_code)
            if canon:
                return canon, 0.92
            reg = get_region_name_by_code(subdivision_code)
            if reg:
                return f"ОТДЕЛОМ ВНУТРЕННИХ ДЕЛ ({reg.upper()})", 0.70
        return "", 0.10

    # 3. Нормализация текста органа выдачи
    res = raw_clean.upper()
    # Убираем ошибочные цифровые вкрапления внутри буквенного названия
    res = re.sub(r'\b\d{1,6}\b', '', res)
    res = re.sub(r'[\r\n\t]+', ' ', res)
    res = re.sub(r'\s+', ' ', res).strip()

    # Оценка уверенности
    confidence = 0.92 if has_indicator else 0.70
    if subdivision_code:
        reg_name = get_region_name_by_code(subdivision_code)
        if reg_name:
            reg_root = reg_name.split()[0][:5].upper()
            if reg_root in res:
                confidence = min(0.99, confidence + 0.06)

    return res, confidence

